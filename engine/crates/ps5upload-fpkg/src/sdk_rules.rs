//! What goes into a package, and what size class it declares.
//!
//! Two sets of rules learned from reading a third-party build kit (sdk-fpkg279), which
//! feeds Sony's Publishing Tools; this is an independent implementation of them.
//!
//! - **Leftovers from an earlier build.** A folder dumped off a console, or extracted from
//!   a package, carries files the packaging step itself generates: PlayGo tables, image
//!   digests, patch delta/reloc data, license files, the `sce_suppl` and `sce_sc` trees.
//!   Packaging them again carries stale copies next to the fresh ones, so they are left
//!   out. The kit also drops what Sony's tool regenerates from other inputs (`.dds`
//!   renders, `about/right.sprx`, `keystone`, `pfs-version.dat`, `ext_info.dat`); this
//!   builder regenerates none of those, so it keeps the source's copies.
//! - **Size class.** `attributePub` declares which large-package level a title needs, and
//!   `kernel.addcontMountLevel` has to be compatible with it. The level is chosen from the
//!   unpacked size with a safety allowance, exactly as the kit chooses it.

use crate::source;

/// `sce_sys/<name>` files the packaging step generates.
const GENERATED_SCE_SYS_FILES: &[&str] = &[
    "disc_info.dat",
    "imagedigs.dat",
    "license.info",
    "license.dat",
    "playgo-chunk.dat",
    "playgo-hash-table.dat",
    "playgo-ficm.dat",
    "playgo-scenario.json",
    "playgo-manifest.xml",
    "playgo-chunk.crc",
    "pfsimage.xml",
    "pfs-region-hints.json",
    "param.sfo",
    "param_cp_values.json",
    "pronunciation.sig",
    "origin-deltainfo.dat",
    "target-deltainfo.dat",
    "origin-param.json",
    "target-param.json",
    "origin-relocinfo.dat",
    "target-relocinfo.dat",
];
/// Top-level trees the publishing tools reserve.
const GENERATED_ROOT_DIRECTORIES: &[&str] = &["sce_suppl", "sce_sc"];
/// Build-project files that sometimes sit in a game folder.
const PROJECT_SUFFIXES: &[&str] = &[".gp4", ".gp5", ".esbak"];
/// A host emulator's index file.
const EXCLUDED_ROOT_FILES: &[&str] = &["ampr_emu.index"];
/// SDK runtime modules a backport's `fakelib/` must not carry: the console provides them.
const EXCLUDED_FAKE_LIBRARIES: &[&str] = &["libsceampr.sprx", "libsceplaygo.sprx"];

/// Why `path` (a source-relative, `/`-separated path) stays out of the package, or `None`
/// when it belongs in it.
pub fn excluded(path: &str) -> Option<&'static str> {
    let lower = path.to_ascii_lowercase();
    let parts: Vec<&str> = lower.split('/').collect();
    if parts.len() > 1 && GENERATED_ROOT_DIRECTORIES.contains(&parts[0]) {
        return Some("reserved/SDK-generated directory");
    }
    if PROJECT_SUFFIXES.iter().any(|s| lower.ends_with(s)) {
        return Some("build-project file");
    }
    if lower.ends_with(".playgo-scenario.json") {
        return Some("build-project scenario sidecar");
    }
    if EXCLUDED_ROOT_FILES.contains(&lower.as_str()) {
        return Some("host emulator index");
    }
    if let Some(name) = lower.strip_prefix("fakelib/") {
        if EXCLUDED_FAKE_LIBRARIES.contains(&name) {
            return Some("SDK runtime module the console provides");
        }
    }
    if parts.len() == 2 && parts[0] == "sce_sys" && GENERATED_SCE_SYS_FILES.contains(&parts[1]) {
        return Some("generated by packaging; a stale copy");
    }
    if parts[0] == "sce_sys" && lower.ends_with(".auth_info") {
        return Some("decryption sidecar from an extraction");
    }
    None
}

const MIB: u64 = 1024 * 1024;
const STANDARD_PACKAGE_LIMIT: u64 = 162_514_599_936;
const LARGE_PACKAGE_LV1_LIMIT: u64 = 195_878_191_104;
const ADDCONT_MOUNT_LV2_LIMIT: u64 = 97_945_387_008;
/// The most files a level-2 package may hold.
pub const LARGE_PACKAGE_LV2_FILE_LIMIT: u64 = 500_000;

/// The size class a title declares.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct SizeClass {
    /// `attributePub`: 0 standard, 1 and 2 the large-package levels.
    pub attribute: u8,
    /// `kernel.addcontMountLevel` after any adjustment the size forces.
    pub mount_level: u8,
    /// The conservative size estimate the choice was made from.
    pub estimated: u64,
}

/// Choose the smallest level that fits `unpacked` bytes in `files` files, keeping the
/// highest add-on mount level the estimate allows. Level 2 is the ceiling: past it the
/// estimate is only an estimate, so the largest class is declared and the build goes on.
pub fn choose_size_class(unpacked: u64, files: u64, mount_level: u8) -> Result<SizeClass, String> {
    if mount_level > 2 {
        return Err(format!(
            "kernel.addcontMountLevel must be 0, 1 or 2, not {mount_level}"
        ));
    }
    let allowance = (512 * MIB).max(unpacked.div_ceil(100)) + files * 4096;
    let estimated = unpacked + allowance;
    let mut level = mount_level;
    if level == 2 && estimated > ADDCONT_MOUNT_LV2_LIMIT {
        level = 1;
    }
    if level == 1 && estimated > LARGE_PACKAGE_LV1_LIMIT {
        level = 0;
    }
    let class = |attribute| SizeClass {
        attribute,
        mount_level: level,
        estimated,
    };
    if level == 2 || estimated <= STANDARD_PACKAGE_LIMIT {
        return Ok(class(0));
    }
    if estimated <= LARGE_PACKAGE_LV1_LIMIT {
        return Ok(class(1));
    }
    if files > LARGE_PACKAGE_LV2_FILE_LIMIT {
        return Err(format!(
            "a package this large holds at most {LARGE_PACKAGE_LV2_FILE_LIMIT} files; this one has {files}"
        ));
    }
    // Level 2 covers 260,436,918,272 bytes. Past that too, the largest class is still
    // declared: the estimate is conservative and the real image may yet fit.
    Ok(class(2))
}

/// The byte span of the number value of the first `key` in `text`.
fn number_value_span(text: &str, key: &str) -> Option<(usize, usize)> {
    let at = text.find(key)? + key.len();
    let colon = at + text[at..].find(':')? + 1;
    let start = colon + text[colon..].len() - text[colon..].trim_start().len();
    let len = text[start..]
        .find(|c: char| !(c.is_ascii_digit() || c == '-'))
        .unwrap_or(text.len() - start);
    (len > 0).then_some((start, start + len))
}

fn set_number(param_json: &[u8], key: &str, value: u64) -> Option<Vec<u8>> {
    let text = String::from_utf8_lossy(param_json);
    let (start, end) = number_value_span(&text, key)?;
    let mut out = param_json[..start].to_vec();
    out.extend_from_slice(value.to_string().as_bytes());
    out.extend_from_slice(&param_json[end..]);
    Some(out)
}

/// `param.json` declaring the size class for `unpacked` bytes in `files` files, with a
/// line saying what changed, or `None` when it already declares it (or is not a native
/// game, whose class this choice does not describe). Only the values' bytes change.
pub fn size_class_rewrite(
    param_json: &[u8],
    unpacked: u64,
    files: u64,
) -> Result<Option<(Vec<u8>, String)>, String> {
    let Some(json) = source::parse_param_json(param_json) else {
        return Ok(None);
    };
    if json.get("applicationCategoryType").and_then(|v| v.as_u64()) != Some(0) {
        return Ok(None);
    }
    let kernel = json.get("kernel");
    let mount_level = kernel
        .and_then(|k| k.get("addcontMountLevel"))
        .and_then(|v| v.as_u64())
        .unwrap_or(0);
    let class = choose_size_class(unpacked, files, mount_level.min(255) as u8)?;
    let current = json.get("attributePub").and_then(|v| v.as_u64());
    let mut out = param_json.to_vec();
    let mut changes = Vec::new();
    if current != Some(class.attribute as u64) {
        out = match current {
            Some(_) => set_number(&out, "\"attributePub\"", class.attribute as u64),
            None => source::insert_raw_field(&out, "attributePub", &class.attribute.to_string()),
        }
        .ok_or("param.json's attributePub could not be rewritten")?;
        changes.push(format!("attributePub={}", class.attribute));
    }
    // The level only ever comes down, so a field that is absent (level 0) never needs adding.
    if u64::from(class.mount_level) != mount_level {
        out = set_number(&out, "\"addcontMountLevel\"", class.mount_level as u64)
            .ok_or("param.json's addcontMountLevel could not be rewritten")?;
        changes.push(format!(
            "kernel.addcontMountLevel {mount_level} -> {}",
            class.mount_level
        ));
    }
    if changes.is_empty() {
        return Ok(None);
    }
    Ok(Some((
        out,
        format!(
            "{} (estimate {:.1} GiB, {files} files)",
            changes.join(", "),
            class.estimated as f64 / (1u64 << 30) as f64
        ),
    )))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn leftovers_are_excluded_and_game_files_are_kept() {
        for p in [
            "sce_sys/param.sfo",
            "sce_sys/playgo-chunk.dat",
            "sce_sys/license.dat",
            "sce_sys/target-deltainfo.dat",
            "sce_sys/eboot.bin.auth_info",
            "sce_suppl/x.bin",
            "sce_sc/keys/a",
            "fakelib/libScePlayGo.sprx",
            "ampr_emu.index",
            "game.gp5",
        ] {
            assert!(excluded(p).is_some(), "{p}");
        }
        for p in [
            "eboot.bin",
            "sce_sys/param.json",
            "sce_sys/keystone",
            "sce_sys/icon0.dds",
            "sce_sys/about/right.sprx",
            "sce_sys/pfs-version.dat",
            "sce_sys/nptitle.dat",
            "sce_sys/trophy2/trophy00.ucp",
            "fakelib/libSceAgc.sprx",
            "data/sce_sys/param.sfo",
            "data/ampr_emu.index",
        ] {
            assert!(excluded(p).is_none(), "{p}");
        }
    }

    #[test]
    fn size_class_follows_the_limits() {
        let gib = 1u64 << 30;
        assert_eq!(choose_size_class(10 * gib, 1000, 0).unwrap().attribute, 0);
        assert_eq!(choose_size_class(170 * gib, 1000, 0).unwrap().attribute, 1);
        assert_eq!(choose_size_class(200 * gib, 1000, 0).unwrap().attribute, 2);
        assert_eq!(choose_size_class(400 * gib, 1000, 0).unwrap().attribute, 2);
        assert!(choose_size_class(200 * gib, 600_000, 0).is_err());
        // A level-2 add-on mount holds up to its own limit, then falls to 1, then to 0.
        let c = choose_size_class(50 * gib, 10, 2).unwrap();
        assert_eq!((c.attribute, c.mount_level), (0, 2));
        let c = choose_size_class(100 * gib, 10, 2).unwrap();
        assert_eq!((c.attribute, c.mount_level), (0, 1));
        let c = choose_size_class(170 * gib, 10, 1).unwrap();
        assert_eq!((c.attribute, c.mount_level), (1, 1));
        let c = choose_size_class(190 * gib, 10, 1).unwrap();
        assert_eq!((c.attribute, c.mount_level), (2, 0));
        // The allowance is 1% or 512 MiB, whichever is more, plus 4 KiB a file.
        let c = choose_size_class(gib, 2, 0).unwrap();
        assert_eq!(c.estimated, gib + 512 * MIB + 8192);
    }

    #[test]
    fn rewrite_inserts_or_replaces_only_the_values() {
        let src = b"{\n  \"applicationCategoryType\": 0,\n  \"kernel\": {\n    \"addcontMountLevel\": 2\n  }\n}\n";
        let (out, why) = size_class_rewrite(src, 100 << 30, 10).unwrap().unwrap();
        let text = String::from_utf8(out).unwrap();
        let v: serde_json::Value = serde_json::from_str(&text).unwrap();
        assert_eq!(v["attributePub"], 0);
        assert_eq!(v["kernel"]["addcontMountLevel"], 1);
        assert!(text.contains("\n  \"attributePub\": 0,\n"), "{text}");
        assert!(why.contains("addcontMountLevel 2 -> 1"), "{why}");
        // A CRLF file gets a CRLF line.
        let crlf = b"{\r\n  \"applicationCategoryType\": 0\r\n}\r\n";
        let (out, _) = size_class_rewrite(crlf, 1 << 30, 1).unwrap().unwrap();
        assert!(out.starts_with(b"{\r\n  \"attributePub\": 0,\r\n  \"application"));
        // Already right: nothing to do.
        let done = b"{\"applicationCategoryType\": 0, \"attributePub\": 0}";
        assert!(size_class_rewrite(done, 1 << 30, 1).unwrap().is_none());
        // Not a native game: left alone.
        let app = b"{\"applicationCategoryType\": 65536}";
        assert!(size_class_rewrite(app, 1 << 30, 1).unwrap().is_none());
    }
}
