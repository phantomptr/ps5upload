#[cfg(test)]
mod tests {
    use super::*;
    use sha2::{Digest, Sha256};

    fn sha256(bytes: &[u8]) -> String {
        Sha256::digest(bytes)
            .iter()
            .map(|b| format!("{b:02x}"))
            .collect()
    }

    /// Fingerprints of the plain values, so a bad paste fails loudly instead of
    /// producing packages with a wrong signature.
    #[test]
    fn key_material_fingerprints() {
        let expected: [(&str, &str); 9] = [
            (
                "PASSCODE_MODULI[0]",
                "6c816fbf1e60a0e72a28cddeeba4dc4c3015bde2a87d550514614499b3ebb293",
            ),
            (
                "PASSCODE_MODULI[1]",
                "ffe4d2e27f06baf7c988c538978f3cbd5d710be515015541d1f643329974578e",
            ),
            (
                "PASSCODE_MODULI[2]",
                "92aec135409cccc0b8f7c3977cad2f0beb435dfb9187d31eefe6afb5ffd177db",
            ),
            (
                "PASSCODE_MODULI[3]",
                "4a585ee47fea88d6b121d5e8afc9829438a27ee325cebec56a2ff537129a37c5",
            ),
            (
                "PASSCODE_MODULI[4]",
                "541b30995c028fd89366c3b1c1dbde70a23fa2784eecfb3fd3dd732502c665fc",
            ),
            (
                "PASSCODE_MODULI[5]",
                "54c7757e8142b538f6b0b1a2fbfd343a05c7158f2d5d5ce144934de5536cb175",
            ),
            (
                "PASSCODE_MODULI[6]",
                "bcbe73d512d460c5b7002ceecc47fdf77d08567cb17cd08e3e05ca02fdc9038c",
            ),
            (
                "MOUNT_IMAGE_MODULUS",
                "4510462812321cea26b4c0155e363955b16e31b89252b92510accad02eca5cd0",
            ),
            (
                "METADATA_MODULUS",
                "4a585ee47fea88d6b121d5e8afc9829438a27ee325cebec56a2ff537129a37c5",
            ),
        ];
        for (i, slot) in PASSCODE_MODULI.chunks(384).enumerate() {
            let (name, want) = expected[i];
            assert_eq!(sha256(slot), want, "{name}");
        }
        assert_eq!(sha256(&MOUNT_IMAGE_MODULUS), expected[7].1);
        assert_eq!(sha256(&METADATA_MODULUS), expected[8].1);
    }

    /// The metadata modulus is the first 384 bytes of the passcode set's slot 3.
    #[test]
    fn metadata_modulus_is_a_passcode_slot() {
        assert_eq!(&PASSCODE_MODULI[3 * 384..4 * 384], &METADATA_MODULUS[..]);
    }
}
