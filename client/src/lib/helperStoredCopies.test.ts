import { describe, expect, it, vi } from "vitest";

import type { PmOverview, PmStoredPayload } from "../api/payloadManager";
import type { Translator } from "../state/lang";
import {
  findStoredCopies,
  isHelperFileName,
  parseAutoloadTxt,
  refreshStoredCopies,
  storedCopiesNotices,
  updateStoredCopies,
  type CopyDeps,
  type ReplaceDeps,
} from "./helperStoredCopies";

const tr = ((key: string, a?: unknown, b?: string) => {
  const text = typeof a === "string" ? a : (b ?? key);
  const vars = (typeof a === "object" && a) || {};
  return text.replace(/\{(\w+)\}/g, (_, k: string) => String((vars as Record<string, unknown>)[k] ?? ""));
}) as Translator;

const H = "192.168.0.9";

type Tree = Record<string, Record<string, string | null>>; // dir -> name -> file text (null = dir)

function fakeConsole(tree: Tree, pm: PmOverview = { present: false, error: "refused" }): CopyDeps {
  return {
    pmOverview: async () => pm,
    listDir: async (_h, path) => {
      const d = tree[path];
      if (!d) throw new Error("fs_list_dir_failed_errno_2");
      return Object.entries(d).map(([name, v]) => ({ name, kind: v === null ? "dir" : "file" }));
    },
    readText: async (_h, path) => {
      const i = path.lastIndexOf("/");
      const v = tree[path.slice(0, i)]?.[path.slice(i + 1)];
      if (typeof v !== "string") throw new Error("no file");
      return v;
    },
  };
}

function pmPayload(path: string, slot = ""): PmStoredPayload {
  const filename = path.split("/").pop()!;
  return { path, slot, filename, folder: "", name: "", version: "", source: "", install_source: "" };
}

describe("isHelperFileName", () => {
  it("counts the helper under any of its usual names", () => {
    for (const n of ["ps5upload.elf", "PS5Upload.ELF", "ps5upload-8.5.1.elf", "ps5upload_v9.elf"]) {
      expect(isHelperFileName(n), n).toBe(true);
    }
  });
  it("never the installer daemon or another payload", () => {
    for (const n of ["ps5upload-installer.elf", "kstuff.elf", "elfldr-ps5upload.elf", "ps5upload.bin", "my-ps5upload.elf"]) {
      expect(isHelperFileName(n), n).toBe(false);
    }
  });
});

describe("parseAutoloadTxt", () => {
  it("keeps the files in order, without comments, pauses or blank lines", () => {
    const txt = "# Generated by ps5upload\r\nkstuff.elf\r\n!3000\r\n\r\n  ps5upload.elf  \n/ps5_autoloader/smp.elf\n";
    expect(parseAutoloadTxt(txt)).toEqual(["kstuff.elf", "ps5upload.elf", "smp.elf"]);
  });
});

describe("findStoredCopies", () => {
  it("finds Payload Manager's copy and whether its autoload starts it", async () => {
    const deps = fakeConsole(
      { "/mnt": {} },
      {
        present: true,
        version: "0.6.1",
        payloads: [
          pmPayload("/data/pldmgr/payloads/local/ps5upload/ps5upload.elf", "local/ps5upload"),
          pmPayload("/data/pldmgr/payloads/local/kstuff/kstuff.elf", "local/kstuff"),
        ],
        payloadsError: null,
        autoload: { enabled: true, delay_s: 5, list: ["local/kstuff", "!1000", "local/ps5upload"] },
        autoloadError: null,
      },
    );
    expect(await findStoredCopies(H, deps)).toEqual([
      { path: "/data/pldmgr/payloads/local/ps5upload/ps5upload.elf", place: "payload-manager", atBoot: true },
    ]);
  });

  it("reads an autoloader folder on a USB drive and its autoload.txt", async () => {
    const deps = fakeConsole({
      "/mnt": { usb0: null, usb1: null, sandbox: null },
      "/mnt/usb0/ps5_autoloader": {
        "autoload.txt": "kstuff.elf\n!1000\nps5upload.elf\n",
        "kstuff.elf": "",
        "ps5upload.elf": "",
        "ps5upload-installer.elf": "",
      },
      // A drive root with no autoload.txt: a loose copy there starts nothing.
      "/mnt/usb1": { "ps5upload.elf": "" },
    });
    expect(await findStoredCopies(H, deps)).toEqual([
      { path: "/mnt/usb0/ps5_autoloader/ps5upload.elf", place: "autoloader", atBoot: true },
    ]);
  });

  it("finds /data/ps5_autoloader and a drive root whose autoload.txt names the helper", async () => {
    const deps = fakeConsole({
      "/mnt": { usb0: null },
      "/data/ps5_autoloader": { "autoload.txt": "PS5Upload.elf\n", "PS5Upload.elf": "" },
      "/mnt/usb0": { "autoload.txt": "ps5upload-9.elf\n", "ps5upload-9.elf": "", "ps5upload-old.elf": "" },
    });
    const found = await findStoredCopies(H, deps);
    expect(found.map((c) => c.path).sort()).toEqual([
      "/data/ps5_autoloader/PS5Upload.elf",
      "/mnt/usb0/ps5upload-9.elf",
    ]);
  });

  it("reads Payload Manager's folders when it does not answer", async () => {
    const deps = fakeConsole({
      "/data/pldmgr/payloads": { ps5upload: null, kstuff: null },
      "/data/pldmgr/payloads/ps5upload": { "ps5upload.elf": "", "ps5upload.json": "{}" },
      "/data/pldmgr/payloads/kstuff": { "kstuff.elf": "" },
    });
    expect(await findStoredCopies(H, deps)).toEqual([
      { path: "/data/pldmgr/payloads/ps5upload/ps5upload.elf", place: "payload-manager", atBoot: false },
    ]);
  });

  it("finds nothing on a console without stored copies", async () => {
    expect(await findStoredCopies(H, fakeConsole({}))).toEqual([]);
  });
});

describe("updateStoredCopies", () => {
  const tree: Tree = {
    "/mnt": { usb0: null },
    "/mnt/usb0/ps5_autoloader": { "autoload.txt": "ps5upload.elf\n", "ps5upload.elf": "" },
  };

  it("replaces every copy found, and only those", async () => {
    const replace = vi.fn(async () => "updated" as const);
    const deps: ReplaceDeps = {
      ...fakeConsole(tree, {
        present: true,
        version: "0.5.2",
        payloads: [pmPayload("/data/pldmgr/payloads/ps5upload/ps5upload.elf"), pmPayload("/data/pldmgr/payloads/kstuff/kstuff.elf")],
        payloadsError: null,
        autoload: { enabled: true, delay_s: 0, list: ["ps5upload.elf"] },
        autoloadError: null,
      }),
      replace,
    };
    const results = await updateStoredCopies(H, deps);
    expect(replace.mock.calls.map((c) => (c as unknown[])[1]).sort()).toEqual([
      "/data/pldmgr/payloads/ps5upload/ps5upload.elf",
      "/mnt/usb0/ps5_autoloader/ps5upload.elf",
    ]);
    expect(results.every((r) => r.status === "updated")).toBe(true);
  });

  it("does nothing when nothing is stored", async () => {
    const replace = vi.fn();
    expect(await updateStoredCopies(H, { ...fakeConsole({}), replace })).toEqual([]);
    expect(replace).not.toHaveBeenCalled();
  });

  it("records a failed replace and goes on", async () => {
    const deps: ReplaceDeps = {
      ...fakeConsole({
        "/mnt": { usb0: null },
        "/data/ps5_autoloader": { "ps5upload.elf": "" },
        "/mnt/usb0/ps5_autoloader": { "ps5upload.elf": "" },
      }),
      replace: async (_h, path) => {
        if (path.startsWith("/mnt")) throw new Error("read-only drive");
        return "updated";
      },
    };
    const results = await updateStoredCopies(H, deps);
    expect(results.find((r) => r.copy.path.startsWith("/mnt"))).toMatchObject({
      status: "failed",
      error: "read-only drive",
    });
    expect(results.find((r) => r.copy.path.startsWith("/data"))?.status).toBe("updated");
  });
});

describe("storedCopiesNotices", () => {
  const copy = { path: "/mnt/usb0/ps5_autoloader/ps5upload.elf", place: "autoloader" as const, atBoot: true };

  it("says the version the PS5 starts next, without paths", () => {
    const [n] = storedCopiesNotices([{ copy, status: "updated" }], tr, "9.2.0");
    expect(n.level).toBe("success");
    expect(n.body).not.toContain("/mnt/usb0");
    expect(n.body).toContain("v9.2.0");
  });

  it("says what could not be updated and how to do it by hand", () => {
    const [n] = storedCopiesNotices([{ copy, status: "failed", error: "EROFS" }], tr, "9.2.0");
    expect(n.level).toBe("warning");
    expect(n.body).toContain(copy.path);
    expect(n.body).toContain("Payload Manager under the same name");
    expect(n.body).toContain("EROFS");
  });

  it("is silent when every copy was already current", () => {
    expect(storedCopiesNotices([{ copy, status: "unchanged" }], tr, "9.2.0")).toEqual([]);
  });
});

describe("refreshStoredCopies", () => {
  it("never throws, whatever the console does", async () => {
    const deps: ReplaceDeps = {
      pmOverview: async () => {
        throw new Error("engine down");
      },
      listDir: async () => {
        throw new Error("engine down");
      },
      readText: async () => {
        throw new Error("engine down");
      },
      replace: async () => {
        throw new Error("engine down");
      },
    };
    const notify = vi.fn();
    await expect(refreshStoredCopies(H, deps, tr, "9.2.0", notify)).resolves.toEqual([]);
    expect(notify).not.toHaveBeenCalled();
  });
});
